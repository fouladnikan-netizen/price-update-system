#!/usr/bin/env node
/**
 * Smoke test: publish one approved Website SKU price to the Website API.
 * Never invents a product_code. Requires WEBSITE_API_* in .env.
 */
import { ensureEnv, getWebsiteConfig } from "../apps/api/src/env.ts";
import { PRODUCTS, findProductByCode } from "../apps/api/src/catalog.ts";
import { publishToWebsite } from "../apps/api/src/publish.ts";

ensureEnv();

const productCode = process.env.SMOKE_PRODUCT_CODE?.trim() || "RBR-000002";
const product = findProductByCode(PRODUCTS, productCode);
if (!product) {
  console.error(`Catalog lock: ${productCode} is not an active Website sku in runtime catalog.`);
  process.exit(1);
}

const website = getWebsiteConfig();
if (!website.configured) {
  console.error("WEBSITE_API_BASE_URL / WEBSITE_API_KEY missing.");
  process.exit(1);
}

const brandName = product.brandNames[0] ?? null;
const today = new Date().toISOString().slice(0, 10);
const factoryRial = Number(process.env.SMOKE_FACTORY_RIAL ?? "425000");

const result = await publishToWebsite({
  queueItemId: `smoke-catalog-lock:${productCode}:${today}`,
  productCode,
  brandId: brandName ? `smoke-${brandName}` : null,
  brandName,
  factoryPrice: factoryRial,
  warehousePrice: null,
  unit: "rial_per_kg",
  priceDate: today,
  reviewStatus: "approved",
  autoGenerated: false,
});

console.log(
  JSON.stringify(
    {
      productCode,
      productName: product.name,
      brandName,
      dryRun: result.dryRun,
      status: result.status,
      websiteOperationId: result.websiteOperationId,
      errorMessage: result.errorMessage,
      factory_price_toman: result.payload.factory_price_toman,
    },
    null,
    2,
  ),
);

if (result.status === "failed" || result.status === "rejected") process.exit(1);
